//! Afspilnings-EQ: renders the EQ to Equalizer APO syntax and writes it to the engine's config
//! folder (see engine.rs), which the audio engine watches and reloads instantly. Also finds the old
//! Equalizer APO/Peace configuration so it can be imported.
use crate::engine;
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

#[derive(Deserialize, Debug, Clone)]
pub struct Band {
    pub enabled: bool,
    #[serde(rename = "type")]
    pub kind: String,
    pub freq: f64,
    pub gain: f64,
    pub q: f64,
}

#[derive(Deserialize, Debug, Clone)]
pub struct OutputEq {
    pub enabled: bool,
    pub preamp: f64,
    pub bands: Vec<Band>,
    pub target: Option<String>,
    /// Extra APO lines (crossfeed etc.) generated by the UI; only a safe subset of commands is accepted.
    #[serde(default)]
    pub extra: Vec<String>,
}

const EXTRA_ALLOWED: [&str; 5] = ["Copy:", "Channel:", "Filter:", "Delay:", "Preamp:"];

#[derive(Serialize, Clone, Debug)]
pub struct DeviceApo {
    pub id: String,
    pub name: String,
    pub apo: bool,
}

#[derive(Serialize, Default)]
pub struct EngineStatus {
    pub devices: Vec<DeviceApo>,
    pub available: bool,
    pub running: bool,
    pub apo_installed: bool,
    pub taken_over: bool,
    pub device: Option<String>,
    pub latency_ms: Option<f64>,
    pub reason: Option<String>,
    pub config_dir: Option<String>,
    /// "builtin" | "external" | "none" – see engine::EngineInfo.
    pub kind: String,
    pub bundled: bool,
    pub engine_version: String,
}

pub fn studio_dir() -> PathBuf {
    let base = std::env::var_os("ProgramData").map(PathBuf::from).unwrap_or_else(|| PathBuf::from(r"C:\ProgramData"));
    base.join("GoXLR Studio")
}

pub fn render(eq: &OutputEq, device_name: Option<&str>) -> String {
    let mut out = String::from("# Skrevet af GoXLR Studio – rediger i appen, ikke her.\n");
    match (eq.target.as_deref(), device_name) {
        (Some(id), _) if id.contains('{') => {
            // Endpoint ids end in the device GUID, which APO's Device: selector matches.
            let guid = &id[id.rfind('{').unwrap_or(0)..];
            out.push_str(&format!("Device: {guid}\n"));
        }
        (_, Some(name)) => out.push_str(&format!("Device: {name}\n")),
        _ => out.push_str("Device: all\n"),
    }
    if !eq.enabled {
        return out;
    }
    out.push_str(&format!("Preamp: {:.1} dB\n", eq.preamp));
    for b in eq.bands.iter().filter(|b| b.enabled) {
        let kind = match b.kind.as_str() {
            "HP" => "HPQ",
            "LP" => "LPQ",
            k => k,
        };
        let has_gain = matches!(b.kind.as_str(), "PK" | "LSC" | "HSC");
        let gain = if has_gain { format!(" Gain {:.1} dB", b.gain) } else { String::new() };
        out.push_str(&format!("Filter: ON {kind} Fc {:.1} Hz{gain} Q {:.3}\n", b.freq, b.q));
    }
    for line in &eq.extra {
        let line = line.trim();
        if !line.contains(['\n', '\r']) && EXTRA_ALLOWED.iter().any(|p| line.starts_with(p)) {
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

pub fn apply(eq: &OutputEq) -> Result<(), String> {
    let dir = engine::config_dir();
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    let name = eq.target.as_deref().and_then(crate::audio::name_of);
    let text = render(eq, name.as_deref());
    // Write next to config.txt and rename, so the engine never reads a half-written file.
    let tmp = dir.join("config.tmp");
    std::fs::write(&tmp, text).map_err(|e| e.to_string())?;
    std::fs::rename(tmp, dir.join("config.txt")).map_err(|e| e.to_string())
}

pub fn status() -> EngineStatus {
    let info = engine::info();
    let devices: Vec<DeviceApo> = info.devices.iter().map(|d| DeviceApo { id: d.id.clone(), name: d.name.clone(), apo: d.installed }).collect();
    let on_any = devices.iter().any(|d| d.apo);
    let running = info.kind != "none" && info.uses_our_config && on_any;
    let reason = match info.kind.as_str() {
        "none" if info.bundled => Some("EQ-motoren er ikke installeret endnu. Vælg udgange og tryk \"Installér EQ-motor\" – det kræver administrator-adgang én gang.".to_string()),
        "none" => Some("Denne version indeholder ikke EQ-motoren.".to_string()),
        "external" if info.bundled => Some("Equalizer APO er installeret separat. GoXLR Studio kan erstatte den med sin indbyggede motor – dine Peace-presets gemmes først.".to_string()),
        "external" if !info.uses_our_config => Some("Equalizer APO er installeret. Tryk \"Brug den eksisterende motor\" for at lade GoXLR Studio styre EQ'en.".to_string()),
        _ if !on_any => Some("Motoren er ikke sat på nogen udgang endnu – vælg udgange nedenfor.".to_string()),
        _ if !info.uses_our_config => Some("Motoren læser ikke GoXLR Studios EQ. Tryk \"Reparér\".".to_string()),
        _ => None,
    };
    EngineStatus {
        devices,
        available: info.kind != "none" || info.bundled,
        running,
        apo_installed: info.kind != "none",
        taken_over: info.uses_our_config,
        device: None,
        latency_ms: Some(0.0),
        reason,
        config_dir: Some(engine::config_dir().display().to_string()),
        kind: info.kind,
        bundled: info.bundled,
        engine_version: info.version,
    }
}

/// Folders that may hold the old Equalizer APO/Peace configuration: a separate installation's
/// config folder, and copies GoXLR Studio saved before it uninstalled Equalizer APO.
pub fn original_config_dirs() -> Vec<PathBuf> {
    let mut dirs = Vec::new();
    if let Some(d) = engine::info().external_config {
        dirs.push(PathBuf::from(d));
    }
    let mut backups: Vec<PathBuf> = std::fs::read_dir(studio_dir())
        .map(|rd| rd.flatten().map(|e| e.path()).filter(|p| p.file_name().map(|n| n.to_string_lossy().starts_with("apo-backup-")).unwrap_or(false)).collect())
        .unwrap_or_default();
    backups.sort();
    backups.reverse();
    dirs.extend(backups.into_iter().map(|b| b.join("config")).filter(|p| p.is_dir()));
    dirs
}

pub fn original_config_dir() -> Option<PathBuf> {
    original_config_dirs().into_iter().next()
}

pub fn read_current_config() -> Result<String, String> {
    let dir = original_config_dir().ok_or("Fandt ingen Equalizer APO-opsætning")?;
    // Older GoXLR Studio versions replaced config.txt and kept the original next to it.
    let old = dir.join("config.txt.goxlr-studio-backup");
    let main = if old.exists() { old } else { dir.join("config.txt") };
    let mut out = String::new();
    expand(&main, &dir, &mut out, 0)?;
    Ok(out)
}

fn expand(file: &Path, base: &Path, out: &mut String, depth: u8) -> Result<(), String> {
    if depth > 8 {
        return Ok(());
    }
    let text = std::fs::read_to_string(file).map_err(|e| format!("{}: {e}", file.display()))?;
    out.push_str(&format!("# ---- {} ----\n", file.display()));
    for line in text.lines() {
        if let Some(rest) = line.trim().trim_start_matches('\u{feff}').strip_prefix("Include:") {
            let p = PathBuf::from(rest.trim());
            let p = if p.is_absolute() { p } else { base.join(p) };
            let _ = expand(&p, p.parent().unwrap_or(base), out, depth + 1);
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    Ok(())
}

#[derive(Serialize)]
pub struct ConfigFile {
    pub name: String,
    pub text: String,
}

/// Every Peace/APO preset file (Peace saves presets as .txt in APO's config folder).
pub fn list_configs() -> Result<Vec<ConfigFile>, String> {
    let dirs = original_config_dirs();
    if dirs.is_empty() {
        return Err("Fandt ingen Equalizer APO/Peace-presets".into());
    }
    let mut out: Vec<ConfigFile> = Vec::new();
    for dir in dirs {
        let mut stack = vec![dir.clone()];
        while let Some(d) = stack.pop() {
            let Ok(rd) = std::fs::read_dir(&d) else { continue };
            for e in rd.flatten() {
                let p = e.path();
                if p.is_dir() {
                    if stack.len() < 32 {
                        stack.push(p);
                    }
                    continue;
                }
                let is_txt = p.extension().map(|x| x.eq_ignore_ascii_case("txt")).unwrap_or(false);
                let name = p.file_stem().map(|s| s.to_string_lossy().to_string()).unwrap_or_default();
                if !is_txt || name.eq_ignore_ascii_case("config") || p.metadata().map(|m| m.len() > 512 * 1024).unwrap_or(true) {
                    continue;
                }
                let rel = p.strip_prefix(&dir).unwrap_or(&p).with_extension("").display().to_string();
                if out.iter().any(|c| c.name.eq_ignore_ascii_case(&rel)) {
                    continue;
                }
                if let Ok(text) = std::fs::read_to_string(&p) {
                    out.push(ConfigFile { name: rel, text });
                }
            }
        }
    }
    out.sort_by(|a, b| a.name.to_lowercase().cmp(&b.name.to_lowercase()));
    Ok(out)
}
