pub fn studio_dir() -> PathBuf {
    let base = std::env::var_os("ProgramData").map(PathBuf::from).unwrap_or_else(|| PathBuf::from(r"C:\ProgramData"));
    base.join("GoXLR Studio")
}

/// What Equalizer APO's "Device:" matches for an endpoint: the GUID at the end of its id, or its
/// name (`name_of`) for ids without one. Semicolons would split the selector, so they are dropped.
fn selector(id: &str, name_of: &dyn Fn(&str) -> Option<String>) -> Option<String> {
    if let Some(i) = id.rfind('{') {
        return Some(id[i..].replace(';', ""));
    }
    name_of(id).map(|n| n.replace(';', " "))
}

#[cfg_attr(not(test), allow(dead_code))]
pub fn render(eq: &OutputEq, device_name: Option<&str>) -> String {
    render_with(eq, device_name, &|_| None)
}

pub fn render_with(eq: &OutputEq, device_name: Option<&str>, name_of: &dyn Fn(&str) -> Option<String>) -> String {
    // ASCII only: Equalizer APO's editor and other tools may read the file as ANSI (fejl: "â€“").
    let mut out = String::from("# Skrevet af GoXLR Studio - rediger i appen, ikke her.\n");
    if eq.enabled && (eq.devices.is_some() || !eq.channels.is_empty()) {
        // EQ pr. kanal: the main EQ on its outputs, then one section per channel. Lines after a
        // "Device:" line only apply to the outputs it names, so every output gets one EQ.
        let main: Vec<String> = eq.devices.iter().flatten().filter_map(|id| selector(id, name_of)).collect();
        if !main.is_empty() {
            out.push_str(&format!("Device: {}\n", main.join("; ")));
            body(&mut out, eq.preamp, &eq.graphic, &eq.bands, &eq.extra, eq.surround, eq.denoise);
            push_dynamics(&mut out, eq.dynamics);
        }
        for c in eq.channels.iter().filter(|c| c.enabled) {
            if let Some(sel) = selector(&c.target, name_of) {
                out.push_str(&format!("Device: {sel}\n"));
                body(&mut out, c.preamp, &c.graphic, &c.bands, &c.extra, c.surround, c.denoise);
                push_dynamics(&mut out, eq.dynamics);
            }
        }
        return out;
    }
    match (eq.target.as_deref(), device_name) {
        (Some(id), _) if id.contains('{') => {
            // Endpoint ids end in the device GUID, which APO's Device: selector matches.
            let guid = &id[id.rfind('{').unwrap_or(0)..];
            out.push_str(&format!("Device: {guid}\n"));
        }
        (_, Some(name)) => out.push_str(&format!("Device: {name}\n")),
        _ => out.push_str("Device: all\n"),
    }
    if !eq.enabled {
        return out;
    }
    body(&mut out, eq.preamp, &eq.graphic, &eq.bands, &eq.extra, eq.surround, eq.denoise);
    push_dynamics(&mut out, eq.dynamics);
    out
}

/// Dynamik last in a section: after the EQ, FIR, crossfeed and virtual speakers.
fn push_dynamics(out: &mut String, d: Option<Dynamics>) {
    if let Some(d) = d {
        out.push_str(&dynamics_line(&engine::dynamics_path().display().to_string(), &d));
    }
}

/// "GraphicEQ: 31 2; 62 1.5; …" – numbers rounded to 2 decimals, without trailing zeros.
fn graphic_line(points: &[(f64, f64)]) -> Option<String> {
    let num = |v: f64| {
        let r = (v * 100.0).round() / 100.0;
        if r == 0.0 { "0".to_string() } else { format!("{r}") }
    };
    let pts: Vec<String> = points.iter().filter(|(f, g)| f.is_finite() && g.is_finite() && *f > 0.0).map(|(f, g)| format!("{} {}", num(*f), num(*g))).collect();
    if pts.is_empty() { None } else { Some(format!("GraphicEQ: {}", pts.join("; "))) }
}

fn body(out: &mut String, preamp: f64, graphic: &[(f64, f64)], bands: &[Band], extra: &[String], surround: Option<crate::surround::Surround>, denoise: bool) {
    // First: noise removal works best on the untouched voices (RNNoise is made for 48 kHz only).
    if denoise {
        out.push_str(&denoise_lines(&crate::engine::denoise_path().display().to_string()));
    }
    out.push_str(&format!("Preamp: {:.1} dB\n", preamp));
    if let Some(line) = graphic_line(graphic) {
        out.push_str(&line);
        out.push('\n');
    }
    filters(out, bands.iter().filter(|b| b.enabled && b.ear().is_none()));
    // One ear only: lines after "Channel: L" apply to the left channel until the next "Channel:".
    let mut ears = false;
    for ear in ["L", "R"] {
        let own: Vec<&Band> = bands.iter().filter(|b| b.enabled && b.ear() == Some(ear)).collect();
        if !own.is_empty() {
            out.push_str(&format!("Channel: {ear}"));
            out.push('\n');
            filters(out, own.into_iter());
            ears = true;
        }
    }
    if ears {
        out.push_str("Channel: all");
        out.push('\n');
    }
    for line in extra {
        let line = line.trim();
        if !line.contains(['\n', '\r']) && (EXTRA_ALLOWED.iter().any(|p| line.starts_with(p)) || fir_line_ok(line)) {
            out.push_str(line);
            out.push('\n');
        }
    }
    // Last, after the EQ: the virtual speakers (they mix the two channels, like crossfeed).
    if let Some(s) = surround {
        for line in crate::surround::lines(s) {
            out.push_str(&line);
            out.push('\n');
        }
    }
}

/// The plugin on the selected output, only at 48 kHz (anything else and it is left out).
pub fn denoise_lines(dll: &str) -> String {
    format!("If: sampleRate == 48000\nVSTPlugin: Library \"{dll}\"\nEndIf:\n")
}

fn filters<'a>(out: &mut String, bands: impl Iterator<Item = &'a Band>) {
    for b in bands {
        let kind = match b.kind.as_str() {
            "HP" => "HPQ",
            "LP" => "LPQ",
            k => k,
        };
        let has_gain = matches!(b.kind.as_str(), "PK" | "LSC" | "HSC");
        let gain = if has_gain { format!(" Gain {:.1} dB", b.gain) } else { String::new() };
        out.push_str(&format!("Filter: ON {kind} Fc {:.1} Hz{gain} Q {:.3}\n", b.freq, b.q));
    }
}

pub fn apply(eq: &OutputEq) -> Result<(), String> {
    let dir = engine::config_dir();
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    let name = eq.target.as_deref().and_then(crate::audio::name_of);
    // The noise-suppression plugin only where it is installed (an older engine install may lack it).
    let mut eq = eq.clone();
    if !crate::engine::denoise_path().exists() {
        eq.denoise = false;
        eq.channels.iter_mut().for_each(|c| c.denoise = false);
    }
    // Dynamik only where its plugin is installed (added by "Test EQ-motoren" on older installs).
    if !crate::engine::dynamics_path().exists() {
        eq.dynamics = None;
    }
    if !crate::engine::voice_path().exists() {
        eq.mic = None;
    }
    // An older plugin (from before Stemmeisolering) gets the strong noise suppression instead,
    // until "Opdatér" has put the new one in.
    if let Some(m) = eq.mic.as_mut() {
        if m.isolate && crate::engine::plugin_outdated(crate::engine::VOICE_DLL) {
            m.isolate = false;
            m.noise = 1.0;
        }
    }
    let eq = &eq;
    let mut text = render_with(eq, name.as_deref(), &|id| crate::audio::name_of(id));
    // Ren mikrofon: split by stage when the engine is on a microphone (or the mic part is wanted).
    if eq.mic.is_some() || !crate::engine::installed_mic_guids().is_empty() {
        text = with_mic(&text, eq.mic.as_ref(), &crate::engine::voice_path().display().to_string(), &|id| crate::audio::name_of(id));
    }
    // Virtuelle højttalere: the impulse files must be there before the config names them.
    let wanted: Vec<crate::surround::Surround> = if eq.enabled { eq.surround.into_iter().chain(eq.channels.iter().filter(|c| c.enabled).filter_map(|c| c.surround)).collect() } else { Vec::new() };
    crate::surround::ensure_files(&dir, &wanted)?;
    // Write next to config.txt and rename, so the engine never reads a half-written file.
    let tmp = dir.join("config.tmp");
    std::fs::write(&tmp, text).map_err(|e| e.to_string())?;
    std::fs::rename(tmp, dir.join("config.txt")).map_err(|e| e.to_string())
}

pub fn status() -> EngineStatus {
    let info = engine::info();
    let devices: Vec<DeviceApo> = info.devices.iter().map(|d| DeviceApo { id: d.id.clone(), name: d.name.clone(), apo: d.installed }).collect();
    let on_any = devices.iter().any(|d| d.apo);
    let registered = info.registration.ok;
    let running = info.kind != "none" && info.uses_our_config && on_any && registered;
    let reason = match info.kind.as_str() {
        "builtin" if !registered => Some(format!(
            "Motoren er ikke registreret korrekt i Windows, så EQ'en høres ikke ({}). Tryk \"Reparér EQ-motoren\".",
            info.registration.problems.iter().map(|p| p.text.as_str()).collect::<Vec<_>>().join("; ")
        )),
        "none" if info.bundled => Some("EQ-motoren er ikke installeret endnu. Vælg udgange og tryk \"Installér EQ-motor\" – det kræver administrator-adgang én gang.".to_string()),
        "none" => Some("Denne version indeholder ikke EQ-motoren.".to_string()),
        "external" if info.bundled => Some("Equalizer APO er installeret separat. GoXLR Studio kan erstatte den med sin indbyggede motor – dine Peace-presets gemmes først.".to_string()),
        "external" if !info.uses_our_config => Some("Equalizer APO er installeret. Tryk \"Brug den eksisterende motor\" for at lade GoXLR Studio styre EQ'en.".to_string()),
        _ if !on_any => Some("Motoren er ikke sat på nogen udgang endnu – vælg udgange nedenfor.".to_string()),
        _ if !info.uses_our_config => Some("Motoren læser ikke GoXLR Studios EQ. Tryk \"Reparér\".".to_string()),
        _ => None,
    };
    EngineStatus {
        devices,
        available: info.kind != "none" || info.bundled,
        running,
        apo_installed: info.kind != "none",
        taken_over: info.uses_our_config,
        device: None,
        latency_ms: Some(0.0),
        reason,
        config_dir: Some(engine::config_dir().display().to_string()),
        kind: info.kind,
        bundled: info.bundled,
        engine_version: info.version,
    }
}

/// Folders that may hold the old Equalizer APO/Peace configuration: a separate installation's
/// config folder, and copies GoXLR Studio saved before it uninstalled Equalizer APO.
pub fn original_config_dirs() -> Vec<PathBuf> {
    let mut dirs = Vec::new();
    if let Some(d) = engine::info().external_config {
        dirs.push(PathBuf::from(d));
    }
    let mut backups: Vec<PathBuf> = std::fs::read_dir(studio_dir())
        .map(|rd| rd.flatten().map(|e| e.path()).filter(|p| p.file_name().map(|n| n.to_string_lossy().starts_with("apo-backup-")).unwrap_or(false)).collect())
        .unwrap_or_default();
    backups.sort();
    backups.reverse();
    dirs.extend(backups.into_iter().map(|b| b.join("config")).filter(|p| p.is_dir()));
    // The Overflytning page's full backups (%APPDATA%\GoXLR Studio\backup\<tid>) hold a copy too –
    // the only one left when Equalizer APO was uninstalled some other way.
    let mut full: Vec<PathBuf> = std::fs::read_dir(crate::migrate::backup_root())
        .map(|rd| rd.flatten().map(|e| e.path().join("Equalizer APO config")).filter(|p| p.is_dir()).collect())
        .unwrap_or_default();
    full.sort();
    full.reverse();
    dirs.extend(full);
    dirs
}

/// Reads a text file the way Notepad does: UTF-16 or UTF-8 with a BOM, UTF-8, otherwise ANSI
/// (Windows-1252). Peace saves its presets as ANSI, so a device name like "Højttalere" made
/// `read_to_string` fail and the preset was skipped without a word.
pub fn read_text(path: &Path) -> Result<String, String> {
    let bytes = std::fs::read(path).map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(decode_text(&bytes))
}

pub fn decode_text(bytes: &[u8]) -> String {
    let utf16 = |b: &[u8], le: bool| {
        let units: Vec<u16> = b.chunks_exact(2).map(|c| if le { u16::from_le_bytes([c[0], c[1]]) } else { u16::from_be_bytes([c[0], c[1]]) }).collect();
        String::from_utf16_lossy(&units)
    };
    if let Some(b) = bytes.strip_prefix(&[0xFF, 0xFE]) {
        return utf16(b, true);
    }
    if let Some(b) = bytes.strip_prefix(&[0xFE, 0xFF]) {
        return utf16(b, false);
    }
    let b = bytes.strip_prefix(&[0xEF, 0xBB, 0xBF]).unwrap_or(bytes);
    // UTF-16 without a BOM: every other byte of ASCII text is 0.
    if b.len() >= 4 && b.len() % 2 == 0 && b.iter().skip(1).step_by(2).take(64).all(|&x| x == 0) && b[0] != 0 {
        return utf16(b, true);
    }
    match std::str::from_utf8(b) {
        Ok(s) => s.to_string(),
        Err(_) => b.iter().map(|&c| cp1252(c)).collect(),
    }
}

fn cp1252(c: u8) -> char {
    const HIGH: [char; 32] = [
        '€', '\u{81}', '‚', 'ƒ', '„', '…', '†', '‡', 'ˆ', '‰', 'Š', '‹', 'Œ', '\u{8d}', 'Ž', '\u{8f}', '\u{90}', '‘', '’', '“', '”', '•', '–', '—', '˜', '™', 'š', '›', 'œ', '\u{9d}', 'ž', 'Ÿ',
    ];
    match c {
        0x80..=0x9F => HIGH[(c - 0x80) as usize],
        _ => c as char,
    }
}

pub fn original_config_dir() -> Option<PathBuf> {
    original_config_dirs().into_iter().next()
}

pub fn read_current_config() -> Result<String, String> {
    let dirs = original_config_dirs();
    if dirs.is_empty() {
        return Err("Fandt ingen Equalizer APO-opsætning".into());
    }
    let mut last = String::new();
    for dir in dirs {
        // Older GoXLR Studio versions replaced config.txt and kept the original next to it.
        let old = dir.join("config.txt.goxlr-studio-backup");
        let main = if old.exists() { old } else { dir.join("config.txt") };
        let mut out = String::new();
        match expand(&main, &dir, &mut out, 0) {
            Ok(()) => return Ok(out),
            Err(e) => last = e,
        }
    }
    Err(last)
}

fn expand(file: &Path, base: &Path, out: &mut String, depth: u8) -> Result<(), String> {
    if depth > 8 {
        return Ok(());
    }
    let text = read_text(file)?;
    out.push_str(&format!("# ---- {} ----\n", file.display()));
    for line in text.lines() {
        if let Some(rest) = line.trim().trim_start_matches('\u{feff}').strip_prefix("Include:") {
            let p = PathBuf::from(rest.trim());
            let p = if p.is_absolute() { p } else { base.join(p) };
            let _ = expand(&p, p.parent().unwrap_or(base), out, depth + 1);
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    Ok(())
}

#[derive(Serialize)]
pub struct ConfigFile {
    pub name: String,
    pub text: String,
}

/// Every Peace/APO preset file (Peace saves presets as .txt in APO's config folder).
pub fn list_configs() -> Result<Vec<ConfigFile>, String> {
    let dirs = original_config_dirs();
    if dirs.is_empty() {
        return Err("Fandt ingen Equalizer APO/Peace-presets".into());
    }
    let mut out: Vec<ConfigFile> = Vec::new();
    for dir in dirs {
        let mut stack = vec![dir.clone()];
        while let Some(d) = stack.pop() {
            let Ok(rd) = std::fs::read_dir(&d) else { continue };
            for e in rd.flatten() {
                let p = e.path();
                if p.is_dir() {
                    if stack.len() < 32 {
                        stack.push(p);
                    }
                    continue;
                }
                let is_txt = p.extension().map(|x| x.eq_ignore_ascii_case("txt") || x.eq_ignore_ascii_case("peace")).unwrap_or(false);
                let name = p.file_stem().map(|s| s.to_string_lossy().to_string()).unwrap_or_default();
                if !is_txt || name.eq_ignore_ascii_case("config") || p.metadata().map(|m| m.len() > 512 * 1024).unwrap_or(true) {
                    continue;
                }
                let rel = p.strip_prefix(&dir).unwrap_or(&p).with_extension("").display().to_string();
                if out.iter().any(|c| c.name.eq_ignore_ascii_case(&rel)) {
                    continue;
                }
                if let Ok(text) = read_text(&p) {
                    out.push(ConfigFile { name: rel, text });
                }
            }
        }
    }
    out.sort_by(|a, b| a.name.to_lowercase().cmp(&b.name.to_lowercase()));
    Ok(out)
}

