//! Afspilnings-EQ: renders the EQ to Equalizer APO syntax and writes it to the engine's config
//! folder (see engine.rs), which the audio engine watches and reloads instantly. Also finds the old
//! Equalizer APO/Peace configuration so it can be imported.
use crate::engine;
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

#[derive(Deserialize, Debug, Clone)]
pub struct Band {
    pub enabled: bool,
    #[serde(rename = "type")]
    pub kind: String,
    pub freq: f64,
    pub gain: f64,
    pub q: f64,
    /// Venstre/højre øre: "L" or "R" for one ear only; None/"all" for both.
    #[serde(default)]
    pub channel: Option<String>,
}

impl Band {
    fn ear(&self) -> Option<&'static str> {
        match self.channel.as_deref() {
            Some("L") => Some("L"),
            Some("R") => Some("R"),
            _ => None,
        }
    }
}

#[derive(Deserialize, Debug, Clone)]
pub struct OutputEq {
    pub enabled: bool,
    pub preamp: f64,
    pub bands: Vec<Band>,
    pub target: Option<String>,
    /// Extra APO lines (crossfeed etc.) generated by the UI; only a safe subset of commands is accepted.
    #[serde(default)]
    pub extra: Vec<String>,
    /// GraphicEQ points (frequency Hz, gain dB): Peace's sliders and AutoEQ curves, played exactly.
    #[serde(default)]
    pub graphic: Vec<(f64, f64)>,
    /// EQ pr. kanal: the outputs the main EQ applies to when channels have their own EQ (the
    /// channel outputs are left out). None = the old behaviour (`target` or all).
    #[serde(default)]
    pub devices: Option<Vec<String>>,
    /// One section per GoXLR channel with its own preset (Game, Music, Chat, System).
    #[serde(default)]
    pub channels: Vec<ChannelEq>,
    /// Virtuelle højttalere (surround.rs).
    #[serde(default)]
    pub surround: Option<crate::surround::Surround>,
    /// Remove noise from the voices (RNNoise VST plugin, see engine::DENOISE_DLL).
    #[serde(default)]
    pub denoise: bool,
    /// Dynamik: GoXLR Studio's own limiter/compressor plugin (plugins/dynamics), last on every output.
    #[serde(default)]
    pub dynamics: Option<Dynamics>,
    /// Ren mikrofon: echo and noise removal on the microphone(s) (plugins/voiceclean).
    #[serde(default)]
    pub mic: Option<MicClean>,
}

/// "Ren mikrofon" on the microphones the engine is on (normally the GoXLR's "Chat Mic").
#[derive(Deserialize, Debug, Clone, PartialEq)]
pub struct MicClean {
    /// Capture endpoint ids ({0.0.1.00000000}.{guid}).
    pub devices: Vec<String>,
    pub echo: bool,
    /// 0 = off, 0.5 = normal, 1 = strong (the plugin's normalized "Noise" parameter).
    pub noise: f64,
    #[serde(default = "yes")]
    pub high_pass: bool,
    /// Stemmeisolering (DeepFilterNet 3 in the plugin). Written only when on, so a plugin from
    /// before 0.14 never sees a parameter it does not know.
    #[serde(default)]
    pub isolate: bool,
}

fn yes() -> bool {
    true
}

/// The "VSTPlugin:" line for the Ren mikrofon plugin.
pub fn voice_line(dll: &str, m: &MicClean) -> String {
    let flag = |b: bool| if b { 1.0 } else { 0.0 };
    let noise = if m.noise.is_finite() { m.noise.clamp(0.0, 1.0) } else { 0.5 };
    let mut line = String::from("VSTPlugin: Library");
    line.push_str(" \"");
    line.push_str(dll);
    line.push('"');
    line.push_str(&format!(" Echo {:.4} Noise {:.4} HighPass {:.4}", flag(m.echo), noise, flag(m.high_pass)));
    if m.isolate {
        line.push_str(" Isolate 1.0000");
    }
    line.push('\n');
    line
}

/// When the engine is on a microphone, Equalizer APO reads this config for the mic too (its
/// "capture" stage), so the playback EQ is kept to the outputs and the mic gets its own part:
/// `If: stage == "capture"` · mic section · `Else:` · playback · `EndIf:`. Without a microphone the
/// config stays exactly as before.
pub fn with_mic(playback: &str, mic: Option<&MicClean>, dll: &str, name_of: &dyn Fn(&str) -> Option<String>) -> String {
    let header_end = playback.find('\n').map(|i| i + 1).unwrap_or(0);
    let (header, rest) = playback.split_at(header_end);
    let mut out = String::from(header);
    out.push_str("If: stage == ");
    out.push('"');
    out.push_str("capture");
    out.push('"');
    out.push('\n');
    if let Some(m) = mic {
        let sel: Vec<String> = m.devices.iter().filter_map(|id| selector(id, name_of)).collect();
        if !sel.is_empty() && (m.echo || m.noise > 0.0 || m.high_pass || m.isolate) {
            out.push_str(&format!("Device: {}\n", sel.join("; ")));
            out.push_str(&voice_line(dll, m));
        }
    }
    out.push_str("Else:\n");
    out.push_str(rest);
    out.push_str("EndIf:\n");
    out
}

/// The plugin's 8 parameters, normalised 0–1 in its order (Thresh, Ratio, Attack, Release, Makeup,
/// LimOn, Ceiling, LimRel – see plugins/dynamics/src/lib.rs).
#[derive(Deserialize, Debug, Clone, Copy, PartialEq)]
pub struct Dynamics {
    pub params: [f64; 8],
}

pub const DYNAMICS_PARAMS: [&str; 8] = ["Thresh", "Ratio", "Attack", "Release", "Makeup", "LimOn", "Ceiling", "LimRel"];

/// The "VSTPlugin:" line for the Dynamik plugin (parameters by name, as Equalizer APO sets them).
pub fn dynamics_line(dll: &str, d: &Dynamics) -> String {
    let mut line = String::from("VSTPlugin: Library");
    line.push_str(" \"");
    line.push_str(dll);
    line.push('"');
    for (n, v) in DYNAMICS_PARAMS.iter().zip(d.params.iter()) {
        line.push_str(&format!(" {n} {:.4}", v.clamp(0.0, 1.0)));
    }
    line.push('\n');
    line
}

