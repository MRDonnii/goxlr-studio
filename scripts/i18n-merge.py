#!/usr/bin/env python3
"""Writes public/js/i18n-en.js from translation files ({ "dansk": "english" } JSON, e.g. from new
texts found with scripts/i18n-extract.py --missing). Existing translations are kept unless a file
gives a new one. Texts that stay the same in English (names, code) go to KEEP.

  python3 scripts/i18n-merge.py new-translations.json [more.json …]
  python3 scripts/i18n-merge.py --prune     # drop texts the code no longer has

scripts/i18n-manual.json holds translations for texts the extractor can't find (always kept).
"""
import json, re, sys, pathlib

OUT = pathlib.Path(__file__).resolve().parent.parent / 'public/js/i18n-en.js'

def load_existing():
    if not OUT.exists():
        return {}, set()
    src = OUT.read_text(encoding='utf-8')
    en = json.loads(re.search(r'export const EN = (\{.*?\});\n', src, re.S).group(1))
    keep = set(json.loads(re.search(r'export const KEEP = (\[.*?\]);\n', src, re.S).group(1)))
    return en, keep

MANUAL = pathlib.Path(__file__).resolve().parent / 'i18n-manual.json'

def current_texts():
    import subprocess
    out = subprocess.run([sys.executable, str(pathlib.Path(__file__).resolve().parent / 'i18n-extract.py')], capture_output=True, text=True, check=True).stdout
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
    ex = __import__('i18n-extract'.replace('-', '_')) if False else None
    return json.loads(out)

def main(files):
    en, keep = load_existing()
    prune = '--prune' in files
    files = [f for f in files if f != '--prune'] + [str(MANUAL)]
    for f in files:
        for da, tr in json.loads(pathlib.Path(f).read_text(encoding='utf-8')).items():
            ph = lambda s: sorted(re.findall(r'\{\d+\}', s))
            if ph(da) != ph(tr):
                sys.exit(f'Pladsholdere passer ikke: {da!r} → {tr!r}')
            if tr == da:
                keep.add(da); en.pop(da, None)
            else:
                en[da] = tr; keep.discard(da)
    if prune:
        import importlib.util
        spec = importlib.util.spec_from_file_location('extract', pathlib.Path(__file__).resolve().parent / 'i18n-extract.py')
        mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
        live = {mod.unescape(k, all(f.endswith('.rs') for f in v)) for k, v in current_texts().items()}
        live |= set(json.loads(MANUAL.read_text(encoding='utf-8')))
        gone = [k for k in en if k not in live] + [k for k in keep if k not in live]
        for k in gone: en.pop(k, None); keep.discard(k)
        print(f'{len(gone)} forældede tekster fjernet')
    head = '// Generated by scripts/i18n-merge.py – English for the Danish UI texts (see i18n.js).\n// Add new texts with scripts/i18n-extract.py --missing → translate → i18n-merge.py.\n'
    body = f'export const EN = {json.dumps(dict(sorted(en.items())), ensure_ascii=False, indent=1)};\nexport const KEEP = {json.dumps(sorted(keep), ensure_ascii=False)};\n'
    OUT.write_text(head + body, encoding='utf-8')
    print(f'{len(en)} oversættelser, {len(keep)} uændrede → {OUT}')

if __name__ == '__main__':
    main(sys.argv[1:])
